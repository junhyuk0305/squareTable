-- 0154_room_last_read.sql — 방별 '어디까지 읽었나' (안 읽은 개수의 근거)
--
-- ── 왜 필요한가 ────────────────────────────────────────────────────────────
-- 채팅방 목록의 안 읽음 배지를 08-19 개편에서 **일부러 안 만들었다** — '내가 언제까지 읽었나'를
--   담는 자리가 스키마에 없어 배지를 그리면 근거 없는 숫자가 되기 때문이다(RoomList 주석).
--   이 컬럼이 그 자리다. 배지와 '안 읽은 순' 정렬이 둘 다 이 값 하나에서 파생된다.
--
-- ── 왜 work_room_prefs 인가 ────────────────────────────────────────────────
-- 읽음 위치는 (사용자 × 방) 축이고, 그 축의 테이블이 이미 0149 에 있다. 새 테이블을 만들면
--   RLS·grant·publication 판단을 한 벌 더 복제하게 된다. 행이 없으면 '기준 없음'이 기본이다.
--
-- ── 기준이 없을 때(null)의 규칙 — 클라와 맞춰야 한다 ──────────────────────
-- null = **안 읽음 0**으로 센다. "가입 이후 전부 안 읽음"으로 세면 첫 로그인에 아무도 안 누른
--   숫자가 방마다 크게 찍힌다(과대보고). 방을 한 번 열면 그때부터 기준이 생겨 정확해진다 —
--   과소보고는 자기교정되지만 과대보고는 안 된다.
--
-- ★쓰기 경로: 클라는 이 컬럼만 담은 upsert 를 쓴다(on conflict 는 준 칼럼만 갱신하므로
--   개인 이름·사진·색을 건드리지 않는다). 반대로 upsertRoomPref 는 이 컬럼을 안 보내므로
--   방 설정 저장이 읽음 위치를 되돌리지 않는다. 두 경로가 서로를 덮지 않는 것이 의도다.

alter table public.work_room_prefs add column if not exists last_read_at timestamptz;

comment on column public.work_room_prefs.last_read_at is
  '이 방을 마지막으로 연 시각(0154). 안 읽은 개수 = 이 시각 이후 남이 쓴 메시지 수. null = 기준 없음 → 0으로 센다.';
