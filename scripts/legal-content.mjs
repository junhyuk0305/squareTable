  <li>이용자는 콘텐츠를 게시함으로써, 회사에 대하여 서비스의 제공·개선·표시·백업 및 AI 결과물 생성(노하우 정리·검색·답변·퀴즈 출제)에 필요한 범위 내에서 이를 저장·복제·수정(형식 변환)·공중송신·전시할 수 있는 무상·비독점의 이용을 허락합니다. 이 이용허락은 서비스 제공 목적에 한하며, 회사는 이를 매장의 동의 없이 외부에 공개하거나 다른 매장에 제공하거나 광고·홍보에 사용하지 않습니다.</li>
