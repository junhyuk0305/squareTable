  <li>이용자는 자신이 등록하는 콘텐츠가 제3자의 지식재산권·초상권·영업비밀 등 권리를 침해하지 않음을 보증하며, 이를 위반하여 분쟁이 발생한 경우 자신의 책임과 비용으로 해결하고 회사를 면책합니다.</li>
