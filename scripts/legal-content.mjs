  <li>회사는 다음 각 호에 해당하는 신청에 대해 승낙을 거부하거나 사후에 이용계약을 해지할 수 있습니다: 타인의 명의·정보를 도용한 경우 / 허위 정보를 기재한 경우 / 만 14세 미만인 경우 / 기타 회사가 정한 이용 신청 요건을 충족하지 못한 경우.</li>
