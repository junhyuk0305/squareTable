<h2>제10조 (AI 기능에 관한 고지)</h2>
<ul>
  <li>서비스는 이용자가 입력한 노하우·질문·문서·음성을 바탕으로 AI가 생성한 결과물(답변·정리·퀴즈 등)을 제공하며, 결과물에는 AI가 생성했음을 표시합니다.</li>
