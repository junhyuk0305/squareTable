  <li>회사는 서비스의 내용·운영상·기술상 필요에 따라 제공 중인 서비스의 전부 또는 일부를 변경할 수 있으며, 무료로 제공되는 서비스를 수정·변경·종료하는 경우 관계 법령에 특별한 규정이 없는 한 이용자에게 별도의 보상을 하지 않습니다.</li>
