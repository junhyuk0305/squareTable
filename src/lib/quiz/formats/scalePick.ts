// ★ 이 형태는 노하우 **한 건으로는 만들 수 없다** — 값이 다른 비슷한 항목 둘이 필요하다.
//   그 쌍을 자동으로 찾아 주는 혼동쌍 탐지(pgvector 임베딩 유사도)는 아직 없다.
//   그래서 지금은 사장이 직접 만드는 경로로만 성립한다 — 자동 출제 후보에서 빠지는 이유는
//   formats/index.ts 의 manualOnly 주석 참고.
//
// ★ payload 모양은 mc4 계열과 같다(choices 2개 + answer_index). 서버 strip 은 공통
//   `- 'answer_index'` 가 그대로 처리하고, 채점도 기존 선택지형 분기에 이름 한 줄만 더하면 된다.
//   손가락 동작이 다를 뿐 데이터는 같은 모양이라 서버에 새 코드를 만들지 않는다.

import { STR, choicePickSpec } from './spec';

export const scalePick = choicePickSpec({
  key: 'scale_pick',
  kind: 't2',
  label: '더 큰 쪽 고르기',
  seconds: 6,
  maxChoices: 2,
  // 무엇을 비교하는지(펌프·도·분) — 정답이 아니므로 응시 화면에도 그대로 보인다.
  extraSchema: { unit: STR },
  aiHint:
    '값이 다른데 서로 헷갈리기 쉬운 항목 **둘**을 골라 choices 에 이름만 담고(예: ["레귤러","라지"]), '
    + 'answer_index 로 값이 더 큰 쪽을 가리켜라. ask 는 무엇을 비교하는지 한 줄로 쓴다'
    + '(예: "시럽이 더 많이 들어가는 쪽은?"). unit 에는 비교하는 단위를 적는다. '
    + '두 항목의 값이 같거나, 노하우에 값이 하나만 있으면 출제하지 마라.',
});
